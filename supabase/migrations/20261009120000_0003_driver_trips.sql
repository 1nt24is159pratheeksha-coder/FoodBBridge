-- Driver accounts are provisioned by an administrator and tied to Supabase Auth.
-- Never accept a driver/user id from the browser as proof of identity.
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE TABLE public.drivers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  phone text,
  vehicle text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'disabled')),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.drivers ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.drivers TO service_role;

ALTER TABLE public.allocations
  ADD COLUMN driver_id uuid REFERENCES public.drivers(id),
  ADD COLUMN pickup_otp_hash text,
  ADD COLUMN delivery_otp_hash text,
  ADD COLUMN pickup_verified_at timestamptz,
  ADD COLUMN delivery_verified_at timestamptz;

UPDATE public.allocations
SET delivery_status = 'Awaiting driver assignment'
WHERE delivery_status IS NULL OR delivery_status IN ('Driver Assignment Pending', 'Pending');
UPDATE public.allocations SET delivery_status = 'Driver Assigned' WHERE delivery_status = 'Accepted';
UPDATE public.allocations SET delivery_status = 'At Pickup' WHERE delivery_status = 'Ready for Pickup';
UPDATE public.allocations SET delivery_status = 'At Delivery' WHERE delivery_status = 'Arrived at Destination';
UPDATE public.allocations SET delivery_status = 'Delivered' WHERE delivery_status = 'Completed';

CREATE TABLE public.driver_trip_responses (
  allocation_id uuid NOT NULL REFERENCES public.allocations(id) ON DELETE CASCADE,
  driver_id uuid NOT NULL REFERENCES public.drivers(id) ON DELETE CASCADE,
  response text NOT NULL CHECK (response IN ('Rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (allocation_id, driver_id)
);
ALTER TABLE public.driver_trip_responses ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.driver_trip_responses TO service_role;

CREATE TABLE public.driver_trip_events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  allocation_id uuid NOT NULL REFERENCES public.allocations(id) ON DELETE CASCADE,
  driver_id uuid NOT NULL REFERENCES public.drivers(id),
  status text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.driver_trip_events ENABLE ROW LEVEL SECURITY;
GRANT ALL ON public.driver_trip_events TO service_role;

CREATE UNIQUE INDEX allocations_one_active_trip_per_driver
  ON public.allocations (driver_id)
  WHERE driver_id IS NOT NULL AND delivery_status <> 'Delivered';

-- Allocation creation is server-only. OTPs are generated by the trusted WhatsApp
-- service, stored as bcrypt hashes, and returned once to the recipient to share
-- with the kitchen. They are never returned by driver trip reads.
CREATE OR REPLACE FUNCTION public.create_driver_allocation(
  p_surplus_id uuid, p_ngo_id uuid, p_quantity integer,
  p_pickup_otp text, p_delivery_otp text
) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions AS $$
DECLARE allocation_id uuid;
BEGIN
  IF p_quantity <= 0 OR p_pickup_otp !~ '^[0-9]{6}$' OR p_delivery_otp !~ '^[0-9]{6}$' THEN
    RAISE EXCEPTION 'Invalid allocation or verification code';
  END IF;
  INSERT INTO public.allocations (surplus_id, ngo_id, quantity, status, delivery_status, pickup_otp_hash, delivery_otp_hash)
  VALUES (p_surplus_id, p_ngo_id, p_quantity, 'ACCEPTED', 'Awaiting driver assignment',
          extensions.crypt(p_pickup_otp, extensions.gen_salt('bf')),
          extensions.crypt(p_delivery_otp, extensions.gen_salt('bf')))
  RETURNING id INTO allocation_id;
  RETURN allocation_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.driver_accept_trip(p_allocation_id uuid, p_driver_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE current_status text;
BEGIN
  PERFORM 1 FROM public.drivers WHERE id = p_driver_id AND status = 'approved' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Driver is not approved'; END IF;
  IF EXISTS (SELECT 1 FROM public.allocations WHERE driver_id = p_driver_id AND delivery_status <> 'Delivered') THEN
    RAISE EXCEPTION 'Driver already has an active trip';
  END IF;
  SELECT delivery_status INTO current_status FROM public.allocations
    WHERE id = p_allocation_id AND status = 'ACCEPTED' FOR UPDATE;
  IF current_status IS DISTINCT FROM 'Awaiting driver assignment' THEN
    RAISE EXCEPTION 'Trip is no longer available';
  END IF;
  UPDATE public.allocations SET driver_id = p_driver_id, delivery_status = 'Driver Assigned', updated_at = now()
    WHERE id = p_allocation_id AND driver_id IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'Trip was already assigned'; END IF;
  INSERT INTO public.driver_trip_events (allocation_id, driver_id, status) VALUES (p_allocation_id, p_driver_id, 'Accepted');
END;
$$;

CREATE OR REPLACE FUNCTION public.driver_reject_trip(p_allocation_id uuid, p_driver_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  PERFORM 1 FROM public.drivers WHERE id = p_driver_id AND status = 'approved';
  IF NOT FOUND THEN RAISE EXCEPTION 'Driver is not approved'; END IF;
  PERFORM 1 FROM public.allocations WHERE id = p_allocation_id AND status = 'ACCEPTED'
    AND delivery_status = 'Awaiting driver assignment' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Trip is no longer available'; END IF;
  INSERT INTO public.driver_trip_responses (allocation_id, driver_id, response)
  VALUES (p_allocation_id, p_driver_id, 'Rejected') ON CONFLICT (allocation_id, driver_id) DO NOTHING;
END;
$$;

CREATE OR REPLACE FUNCTION public.driver_advance_trip(
  p_allocation_id uuid, p_driver_id uuid, p_action text, p_otp text DEFAULT NULL
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions AS $$
DECLARE current_status text; next_status text; expected_otp text;
BEGIN
  SELECT delivery_status, CASE WHEN p_action = 'verify_pickup' THEN pickup_otp_hash
                               WHEN p_action = 'verify_delivery' THEN delivery_otp_hash END
    INTO current_status, expected_otp
    FROM public.allocations WHERE id = p_allocation_id AND driver_id = p_driver_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Trip not found for this driver'; END IF;
  IF p_action = 'arrive_pickup' AND current_status = 'Driver Assigned' THEN next_status := 'At Pickup';
  ELSIF p_action = 'verify_pickup' AND current_status = 'At Pickup' THEN
    IF p_otp IS NULL OR p_otp !~ '^[0-9]{6}$' OR expected_otp IS NULL OR extensions.crypt(p_otp, expected_otp) <> expected_otp THEN
      RAISE EXCEPTION 'Incorrect pickup code';
    END IF;
    next_status := 'Picked Up';
  ELSIF p_action = 'start_transit' AND current_status = 'Picked Up' THEN next_status := 'In Transit';
  ELSIF p_action = 'arrive_delivery' AND current_status = 'In Transit' THEN next_status := 'At Delivery';
  ELSIF p_action = 'verify_delivery' AND current_status = 'At Delivery' THEN
    IF p_otp IS NULL OR p_otp !~ '^[0-9]{6}$' OR expected_otp IS NULL OR extensions.crypt(p_otp, expected_otp) <> expected_otp THEN
      RAISE EXCEPTION 'Incorrect delivery code';
    END IF;
    next_status := 'Delivered';
  ELSE RAISE EXCEPTION 'Invalid trip status transition';
  END IF;
  UPDATE public.allocations
    SET delivery_status = next_status,
        pickup_verified_at = CASE WHEN p_action = 'verify_pickup' THEN now() ELSE pickup_verified_at END,
        delivery_verified_at = CASE WHEN p_action = 'verify_delivery' THEN now() ELSE delivery_verified_at END,
        pickup_otp_hash = CASE WHEN p_action = 'verify_pickup' THEN NULL ELSE pickup_otp_hash END,
        delivery_otp_hash = CASE WHEN p_action = 'verify_delivery' THEN NULL ELSE delivery_otp_hash END,
        updated_at = now()
    WHERE id = p_allocation_id;
  INSERT INTO public.driver_trip_events (allocation_id, driver_id, status)
    VALUES (p_allocation_id, p_driver_id, CASE next_status WHEN 'Driver Assigned' THEN 'Accepted' WHEN 'Delivered' THEN 'Completed' ELSE next_status END);
END;
$$;

REVOKE ALL ON FUNCTION public.create_driver_allocation(uuid, uuid, integer, text, text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.driver_accept_trip(uuid, uuid) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.driver_reject_trip(uuid, uuid) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.driver_advance_trip(uuid, uuid, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_driver_allocation(uuid, uuid, integer, text, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.driver_accept_trip(uuid, uuid) TO service_role;
GRANT EXECUTE ON FUNCTION public.driver_reject_trip(uuid, uuid) TO service_role;
GRANT EXECUTE ON FUNCTION public.driver_advance_trip(uuid, uuid, text, text) TO service_role;
